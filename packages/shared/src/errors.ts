export type V1ErrorCode = (typeof V1_ERROR_CODES)[keyof typeof V1_ERROR_CODES];
export type ErrorCode = (typeof ERROR_CODES)[keyof typeof ERROR_CODES] | V1ErrorCode;

export class WorkmeshError extends Error {
  constructor(
    readonly code: ErrorCode,
    message: string,
    readonly details?: Record<string, unknown>,
    readonly status = 400,
  ) {
    super(message);
    this.name = 'WorkmeshError';
  }
}

export function errorEnvelope(error: WorkmeshError, requestId: string) {
  return {
    error: {
      code: error.code,
      message: error.message,
      ...(error.details ? { details: error.details } : {}),
      requestId,
    },
  };
}
